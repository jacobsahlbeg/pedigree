test('baseline prefers the same release line and settled releases', () => {
  const p = {
    versions: { '0.30.0': {}, '0.30.1': {}, '1.11.0': {}, '1.12.0': {}, '1.12.1': {}, '2.0.0-rc.1': {} },
    time: {
      '0.30.0': '2026-01-01T00:00:00Z',
      '1.11.0': '2026-02-01T00:00:00Z',
      '0.30.1': '2026-03-01T00:00:00Z',
      '1.12.0': '2026-03-10T00:00:00Z',
      '2.0.0-rc.1': '2026-03-11T00:00:00Z',
      '1.12.1': '2026-03-12T00:00:00Z',
    },
  };
  const pick = (v, o) => {
    const b = chooseBaseline(p, v, o);
    return b && { version: b.version, settled: b.settled };
  };
  // 1.12.0 is only 48h older than 1.12.1, so the settled pick moves out to the major line: 1.11.0
  assert.deepEqual(pick('1.12.1', { gapHours: 72 }), { version: '1.11.0', settled: true });
  assert.deepEqual(pick('1.12.1', { gapHours: 24 }), { version: '1.12.0', settled: true });
  assert.deepEqual(pick('0.30.1', { gapHours: 72 }), { version: '0.30.0', settled: true });
  assert.equal(chooseBaseline(p, '0.30.0'), null);
  assert.deepEqual(chooseBaseline(p, '1.12.1', { explicit: '0.30.0' }).version, '0.30.0');
  // history spans the major line first, then widens to other lines until it is full
  assert.deepEqual(chooseBaseline(p, '1.12.1', { gapHours: 24 }).history, ['1.12.0', '1.11.0', '0.30.1', '0.30.0']);
  assert.deepEqual(chooseBaseline(p, '1.12.1', { gapHours: 24, historySize: 2 }).history, ['1.12.0', '1.11.0']);
});

test('baseline picks the nearest lower version, not a backport published later', () => {
  const p = {
    versions: { '19.2.6': {}, '19.2.7': {}, '19.0.7': {}, '19.0.8': {}, '19.3.0': {} },
    time: {
      '19.2.6': '2026-08-01T00:00:00Z',
      '19.2.7': '2026-09-01T00:00:00Z',
      '19.0.7': '2026-09-02T00:00:00Z',
      '19.0.8': '2026-10-01T00:00:00Z',
      '19.3.0': '2026-10-10T00:00:00Z',
    },
  };
  assert.equal(chooseBaseline(p, '19.3.0').version, '19.2.7');
  assert.equal(chooseBaseline(p, '19.0.8').version, '19.0.7');
  assert.equal(releaseLine('0.30.1'), '0.30');
  assert.equal(releaseLine('12.0.0'), '12');
});

// --- reporting and config ------------------------------------------------------------

const sample = [
  {
    name: 'evil', version: '1.0.1', baseline: '1.0.0', maxSeverity: 'critical', error: null,
    provenance: { repository: 'https://github.com/o/r', workflow: 'x.yml', event: 'push', commit: 'abcdef1234567890' },
    findings: [
      { id: 'PD007', rule: 'commit-off-main', severity: 'critical', message: 'orphan | pipe <b>' },
      { id: 'PD016', rule: 'lineage-unchecked', severity: 'info', message: 'n/a' },
    ],
  },
  { name: 'fine', version: '2.0.0', baseline: '1.9.0', maxSeverity: 'info', error: null, provenance: null, findings: [] },
];

test('fail thresholds', () => {
  assert.equal(shouldFail(sample, 'high'), true);
  assert.equal(shouldFail(sample, 'none'), false);
  assert.equal(shouldFail([sample[1]], 'low'), false);
  assert.throws(() => shouldFail(sample, 'severe'));
});

test('markdown report escapes table content and carries the comment marker', () => {
  const md = toMarkdown(sample, { failOn: 'high' });
  assert.ok(md.startsWith(COMMENT_MARKER));
  assert.match(md, /1 of 2 upgraded package\(s\) need review/);
  assert.match(md, /orphan \\\| pipe &lt;b>/);
  assert.match(md, /1 other upgrade\(s\) matched/);
  const text = toText(sample);
  assert.match(text, /CRITICAL evil@1.0.1/);
  assert.match(text, /✓ fine@2.0.0/);
  assert.ok(!text.includes('PD016'), 'info hidden by default');
});

test('ignores need a reason and only drop matching findings', () => {
  assert.throws(() => validateConfig({ ignore: [{ package: 'evil', rule: 'PD007' }] }), /reason/);
  assert.throws(() => validateConfig({ ignore: [{ package: 'evil', rule: 'PD999', reason: 'x' }] }), /rule/);
  const cfg = validateConfig({ ignore: [{ package: 'evil', rule: 'PD007', reason: 'verified with maintainers' }] });
  const [r] = applyIgnores(sample, cfg);
  assert.deepEqual(r.findings.map((f) => f.id), ['PD016']);
  assert.equal(r.maxSeverity, 'info');
  assert.equal(r.ignored, 1);
});
