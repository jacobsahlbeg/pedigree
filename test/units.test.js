test('yarn v1 and berry', () => {
  const v1 = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.1.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.24.0.tgz#abc"
  integrity sha512-x

lodash@^4.17.0:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#def"

my-fork@github:me/fork:
  version "1.0.0"
  resolved "https://codeload.github.com/me/fork/tar.gz/abc"
`;
  assert.equal(detectKind('yarn.lock', v1), 'yarn-v1');
  assert.deepEqual(asObj(parseLockfile('yarn.lock', v1)), { '@babel/core': ['7.24.0'], lodash: ['4.17.21'] });

  const berry = `__metadata:
  version: 8
  cacheKey: 10c0

"@babel/core@npm:^7.0.0":
  version: 7.24.0
  resolution: "@babel/core@npm:7.24.0"
  checksum: 10c0/abc

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."

"lodash@npm:^4.17.0, lodash@npm:^4.17.20":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
`;
  assert.equal(detectKind('yarn.lock', berry), 'yarn-berry');
  assert.deepEqual(asObj(parseLockfile('yarn.lock', berry)), { '@babel/core': ['7.24.0'], lodash: ['4.17.21'] });
});

test('diff reports only newly introduced versions, with what they replaced', () => {
  const base = new Map([['a', new Set(['1.0.0'])], ['b', new Set(['2.0.0'])]]);
  const head = new Map([['a', new Set(['1.1.0'])], ['b', new Set(['2.0.0'])], ['c', new Set(['0.1.0'])]]);
  assert.deepEqual(diffLockfiles(base, head), [
    { name: 'a', version: '1.1.0', previous: ['1.0.0'] },
    { name: 'c', version: '0.1.0', previous: [] },
  ]);
});

// --- provenance ----------------------------------------------------------------------

test('parses SLSA v1 provenance as npm publishes it', () => {
  const p = parseProvenance(provenanceStatement({ repo: 'Sigstore/Sigstore-JS', commit: 'abc123', event: 'push' }));
  assert.equal(p.slsaVersion, 'v1');
  assert.equal(p.repository, 'https://github.com/sigstore/sigstore-js');
  assert.equal(p.owner, 'sigstore');
  assert.equal(p.repo, 'sigstore-js');
  assert.equal(p.workflowPath, '.github/workflows/release.yml');
  assert.equal(p.eventName, 'push');
  assert.equal(p.commit, 'abc123');
  assert.deepEqual(p.ref, { kind: 'branch', name: 'main' });
});

test('parses npm v0.2 provenance', () => {
  const p = parseProvenance({
    predicateType: 'https://slsa.dev/provenance/v0.2',
    predicate: {
      builder: { id: 'https://github.com/actions/runner' },
      invocation: {
        configSource: { uri: 'git+https://github.com/o/r@refs/tags/v1.0.0', digest: { sha1: 'deadbeef' }, entryPoint: '.github/workflows/publish.yml' },
        environment: { GITHUB_EVENT_NAME: 'release', GITHUB_REPOSITORY: 'o/r', GITHUB_RUN_ID: '42' },
      },
    },
  });
  assert.equal(p.slsaVersion, 'v0.2');
  assert.equal(p.repository, 'https://github.com/o/r');
  assert.equal(p.commit, 'deadbeef');
  assert.equal(p.eventName, 'release');
  assert.deepEqual(p.ref, { kind: 'tag', name: 'v1.0.0' });
  assert.equal(p.runUrl, 'https://github.com/o/r/actions/runs/42');
});

test('ref and uri helpers', () => {
  assert.deepEqual(parseRef('refs/pull/12/merge'), { kind: 'pull', name: '12/merge' });
  assert.deepEqual(splitGitUri('git+https://github.com/o/r@refs/heads/dev'), { repo: 'https://github.com/o/r', ref: 'refs/heads/dev' });
});

test('decodes attestation bundles and ignores junk', () => {
  const stmt = provenanceStatement({ repo: 'o/r', commit: 'x' });
  const body = {
    attestations: [
      { predicateType: 'x', bundle: { dsseEnvelope: { payload: 'not base64 json' } } },
      { bundle: { dsseEnvelope: { payload: Buffer.from(JSON.stringify(stmt)).toString('base64') } } },
    ],
  };
  assert.equal(decodeAttestations(body).provenance.predicateType, 'https://slsa.dev/provenance/v1');
  assert.deepEqual(decodeAttestations(null), { provenance: null, publish: null });
});

// --- tarballs ------------------------------------------------------------------------

test('lists tarball files, reads package.json, finds binding.gyp and binaries', () => {
  const longDir = 'deep/'.repeat(25);
  const gz = makeTarball({
    'package.json': JSON.stringify({ name: 'x', scripts: { postinstall: 'node a.js' } }),
    'src/binding.gyp': '{}',
    'prebuilds/linux-x64/x.node': 'ELF',
    [`${longDir}file.js`]: 'long path via pax header',
  });
  const listing = listTarball(gz);
  const paths = listing.files.map((f) => f.path);
  assert.ok(paths.includes('package.json'));
  assert.ok(paths.includes(`${longDir}file.js`), 'pax long path honored');
  assert.equal(listing.packageJson.scripts.postinstall, 'node a.js');
  const s = summarizeTarball(listing);
  assert.equal(s.hasBindingGyp, true);
  assert.deepEqual(s.nativeBinaries, ['prebuilds/linux-x64/x.node']);
});

test('refuses tarballs that expand past the limit', () => {
  const gz = makeTarball({ 'big.txt': 'a'.repeat(100000) });
  assert.throws(() => listTarball(gz, { maxUnpackedBytes: 10000 }));
});

