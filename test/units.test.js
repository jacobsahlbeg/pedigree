const asObj = (map) => Object.fromEntries([...map].map(([k, v]) => [k, [...v].sort()]));

// --- lockfiles ---------------------------------------------------------------------

test('npm lockfile v3', () => {
  const lock = JSON.stringify({
    lockfileVersion: 3,
    packages: {
      '': { name: 'app', version: '1.0.0' },
      'node_modules/lodash': { version: '4.17.21', resolved: 'https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz' },
      'node_modules/@scope/a': { version: '1.0.0', resolved: 'https://registry.npmjs.org/@scope/a/-/a-1.0.0.tgz' },
      'node_modules/@scope/a/node_modules/lodash': { version: '3.10.1', resolved: 'https://registry.npmjs.org/lodash/-/lodash-3.10.1.tgz' },
      'node_modules/local': { resolved: 'packages/local', link: true },
      'node_modules/from-git': { version: '1.0.0', resolved: 'git+ssh://git@github.com/x/y.git#abc' },
      'node_modules/aliased': { name: 'real-name', version: '2.0.0', resolved: 'https://registry.npmjs.org/real-name/-/real-name-2.0.0.tgz' },
    },
  });
  assert.deepEqual(asObj(parseLockfile('package-lock.json', lock)), {
    lodash: ['3.10.1', '4.17.21'],
    '@scope/a': ['1.0.0'],
    'real-name': ['2.0.0'],
  });
});

test('npm lockfile v1', () => {
  const lock = JSON.stringify({
    lockfileVersion: 1,
    dependencies: {
      a: { version: '1.0.0', resolved: 'https://registry.npmjs.org/a/-/a-1.0.0.tgz', dependencies: { b: { version: '2.0.0' } } },
      g: { version: 'github:x/y#abc' },
    },
  });
  assert.deepEqual(asObj(parseLockfile('package-lock.json', lock)), { a: ['1.0.0'], b: ['2.0.0'] });
});

